"""Generate src/tables.rs: HTML5 named character references, Python's Unicode classes and
libxml2's HTML parser tables.

Usage: python scripts/gen_tables.py path/to/libxml2-2.14.x/HTMLparser.c

Run with the Python version the Python parser runs on: its `re` module defines \\d, \\w and
\\s. The libxml2 source must match the version lxml bundles (lxml.etree.LIBXML_VERSION).
"""

import re
import sys
import unicodedata
from html.entities import html5
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "tables.rs"


def ranges(pred):
    out, start = [], None
    for c in range(sys.maxunicode + 2):
        ok = c <= sys.maxunicode and pred(chr(c))
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1))
            start = None
    return out


def rust_str(s: str) -> str:
    return '"' + "".join(c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else f"\\u{{{ord(c):x}}}"
                         for c in s) + '"'


def table(name: str, rs: list[tuple[int, int]]) -> str:
    rows = "".join(f"    (0x{a:x}, 0x{b:x}),\n" for a, b in rs)
    return f"pub const {name}: &[(u32, u32)] = &[\n{rows}];\n"


def libxml2_tables(src: str) -> str:
    elems = src[src.index("html40ElementTable[] = {"):src.index("htmlStartCloseEntry;")]
    rows = re.findall(r'\{ "(\w+)",\s*\d, \d, \d, (\d), \d, \d, \d,[^}]*?(\w+)\s*\}', elems)
    if len(rows) != len(re.findall(r'\{ "\w+",', elems)):
        raise SystemExit("could not parse html40ElementTable")
    modes = {"0": "0", "DATA_RCDATA": "RCDATA", "DATA_RAWTEXT": "RAWTEXT",
             "DATA_PLAINTEXT": "PLAINTEXT", "DATA_SCRIPT": "SCRIPT"}
    empty = [n for n, e, _ in rows if e == "1"]
    data = [(n, modes[m]) for n, _, m in rows if m != "0"]
    close_src = src[src.index("htmlStartClose[] = {"):src.index("htmlScriptAttributes[]")]
    close = re.findall(r'\{ "(\w+)", "(\w+)" \}', close_src)
    if close != sorted(close):
        raise SystemExit("htmlStartClose is not sorted")
    prio_src = src[src.index("htmlEndPriority[] = {"):]
    prio = re.findall(r'\{"(\w+)",\s*(\d+)\}', prio_src[:prio_src.index("NULL")])
    return (
        "\n/// libxml2 elements whose start tag is also their end (htmlElemDesc.empty).\n"
        "pub const EMPTY_ELEMENTS: &[&str] = &[\n"
        + "".join(f'    "{n}",\n' for n in empty) + "];\n\n"
        "/// libxml2 elements whose content is not markup (htmlElemDesc.dataMode).\n"
        "pub const DATA_ELEMENTS: &[(&str, DataMode)] = &[\n"
        + "".join(f'    ("{n}", DataMode::{m.capitalize()}),\n' for n, m in data) + "];\n\n"
        "/// libxml2 htmlStartClose: (open element, start tag that closes it), sorted.\n"
        "pub const START_CLOSE: &[(&str, &str)] = &[\n"
        + "".join(f'    ("{a}", "{b}"),\n' for a, b in close) + "];\n\n"
        "/// libxml2 htmlEndPriority; other elements have priority 100.\n"
        "pub const END_PRIORITY: &[(&str, u8)] = &[\n"
        + "".join(f'    ("{n}", {p}),\n' for n, p in prio) + "];\n"
    )


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    libxml2 = libxml2_tables(Path(sys.argv[1]).read_text())
    entities = sorted(html5.items(), key=lambda kv: kv[0].encode())
    rows = "".join(f"    ({rust_str(k)}, {rust_str(v)}),\n" for k, v in entities)
    OUT.write_text(
        f"// Generated by scripts/gen_tables.py (Python {sys.version.split()[0]}, Unicode "
        f"{unicodedata.unidata_version}, libxml2 HTMLparser.c). Do not edit.\n\n"
        "use crate::html::DataMode;\n\n"
        "/// HTML5 named character references, sorted by name. Names without ';' are the\n"
        "/// legacy ones that may omit it.\n"
        f"pub const ENTITIES: &[(&str, &str)] = &[\n{rows}];\n\n"
        "/// Characters Python's `str.isalnum()` accepts (`re`'s \\w, minus '_').\n"
        + table("ALNUM", ranges(str.isalnum))
        + "\n/// Characters Python's `str.isdecimal()` accepts (`re`'s \\d).\n"
        + table("DECIMAL", ranges(str.isdecimal))
        + "\n/// Characters Python's `str.isspace()` accepts (`re`'s \\s, `str.strip()`).\n"
        + table("SPACE", ranges(str.isspace))
        + libxml2
    )


if __name__ == "__main__":
    main()
