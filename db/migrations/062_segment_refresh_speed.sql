-- The segments refresh, linear again. Since 053 the hourly facts-fetcher-segments job's full pass ran
-- one query at 95% of a core for 2.5+ hours on hermes (2026-11-09). The cause is older than 053 and
-- 053 made it worse: gold.refresh_segment_financials is one statement of CTEs over every company of
-- the call, and a CTE has no index, so its joins and per-row lookups read the whole call's rows each
-- time. Hermes plans `keyed` at one row (facts' join to the metric tags is estimated at 1 row for a
-- company of 3,865 facts), so every join after it is a nested loop:
--
-- - 018's `matches` (equal values of two members for one period): keyed x keyed;
-- - 018's `members`: a sub-select over all of `resolved` per row, for the merged QNames;
-- - 053's `same_basis`: a LATERAL scan of `resolved` per year-to-date row for the first reported
--   value, and a nested-loop join to `resolved` for the same-cycle restatement.
--
-- Each costs (rows of the call)^2: one company of 3,865 facts 4.0 s; 25 companies of the first
-- production batch 83 s; 50 of them more than 11 minutes (cancelled); the job's batches of 25-200
-- documents and the runbook's 200-company batches grow like that.
--
-- 062 (edits to 053's body marked "062", generated by a script asserting each anchor once):
-- 1. One company at a time (a loop over the call's ids, sorted, after the same advisory locks and
--    DELETE). Every step keys on company_id, so the rows are the same.
-- 2. keyed: the canonical QName as a window (first_value in 053's DISTINCT ON order), not a join back.
-- 3. matches: per period and value, the members' fact counts, then the pairs within each value
--    (unnest x unnest); matched = sum of counts a x b, which is the self-join's count(*).
-- 4. members: the merged QNames from one GROUP BY (array_agg DISTINCT ... ORDER BY, '{}' when none).
-- 5. same_basis: the first reported value at a row's priority as a window column of `resolved`
--    (053's LATERAL `o`); the same-cycle row as a LATERAL in 053's DISTINCT ON order with LIMIT 1,
--    whose restated test is a one-time filter, so only a restated value reads `resolved`.
-- 053's rule, 018's merging, renames and TTM are unchanged.
--
-- Measured on production's silver.segment_facts of 222 companies (the runbook's first batch of 200
-- plus the 25 largest, JPM, NVDA, DECK and VRT; 262,473 facts) on a throwaway database: 053 one call
-- per company 95 s in all (the largest 4.0 s), 062 one call for all 222 5.8 s (the largest 0.15 s),
-- and 6.0 s with hash and merge joins disabled (the plan hermes' estimates give). gold rows identical:
-- 135,229 rows (76,397 quarters, 16,453 derived, 58,832 TTM, 21,323 with aliases), every column but
-- refreshed_at, for 053 per company and 062 in one call, in batches of 25 and with nested loops only.
--
-- Locks on hermes: CREATE OR REPLACE FUNCTION, catalog only (lock_timeout 30 s, like 053); no table is
-- locked, read or written, and a segments call already running finishes with 053's body. Nothing
-- stored changes and no refresh is needed: the next call writes the same rows, faster. Backout:
-- db/backout/segments_speed_062.sql (053's body).

SET LOCAL lock_timeout = '30s';

CREATE OR REPLACE FUNCTION gold.refresh_segment_financials(p_company_ids text[]) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    n integer;
    v_company text;  -- 062
BEGIN
    PERFORM pg_advisory_xact_lock(hashtext('gold.segment_financials'), hashtext(id))
    FROM (SELECT DISTINCT id FROM unnest(p_company_ids) id ORDER BY id) ids;

    DELETE FROM gold.segment_financials WHERE company_id = ANY(p_company_ids);

    -- 062: one company at a time. Every step below keys on company_id, so the rows are the same,
    -- but a CTE has no index, so a join or lookup over one read every company of the call: its
    -- cost grew with the square of the call's facts (25 companies: minutes; 200: hours).
    FOR v_company IN SELECT DISTINCT id FROM unnest(p_company_ids) id ORDER BY id LOOP
    WITH RECURSIVE facts AS (
        SELECT k.company_id, f.*, t.priority, m.additive,
               regexp_replace(lower(replace(f.member_label, '&', ' and ')), '[^a-z0-9]+', '',
                              'g') AS label_key
        FROM silver.company_ciks k
        JOIN silver.segment_facts f ON f.cik = k.cik
        JOIN silver.segment_metric_tags t ON t.metric = f.metric AND t.tag = f.concept
        JOIN silver.segment_metrics m ON m.metric = f.metric AND m.unit = f.unit
        WHERE k.company_id = v_company AND f.axis <> 'total'  -- 062
    ),
    keyed AS (  -- 1a: one QName per label key, the one filed most recently
        -- 062: the first member in 053's DISTINCT ON order, as a window, not a join back to facts
        SELECT f.*, first_value(f.member) OVER (
                   PARTITION BY f.company_id, f.axis, f.label_key
                   ORDER BY f.filed DESC, f.accession_no DESC, f.member) AS canon
        FROM facts f
    ),
    spans AS (
        SELECT company_id, axis, canon, min(filed) AS first_filed, max(filed) AS last_filed
        FROM keyed
        GROUP BY company_id, axis, canon
    ),
    -- 062: 053's self-join of keyed, counted per value instead: facts of each member with the
    -- same period and value, and the pairs of members within each such value. matched is the
    -- join's count(*) (a pair of members contributes rows a x rows b).
    same_value AS (
        SELECT company_id, axis, metric, period_start, period_end, value, canon, count(*) AS facts
        FROM keyed
        WHERE value <> 0
        GROUP BY company_id, axis, metric, period_start, period_end, value, canon
    ),
    shared AS (
        SELECT company_id, axis, array_agg(canon) AS canons, array_agg(facts) AS counts
        FROM same_value
        GROUP BY company_id, axis, metric, period_start, period_end, value
        HAVING count(*) > 1
    ),
    pairs AS (
        SELECT s.company_id, s.axis, a.canon AS old, b.canon AS new, a.facts * b.facts AS pairs
        FROM shared s
        CROSS JOIN LATERAL unnest(s.canons, s.counts) a (canon, facts)
        CROSS JOIN LATERAL unnest(s.canons, s.counts) b (canon, facts)
        WHERE b.canon <> a.canon
    ),
    matches AS (  -- 1b: equal values for the same period, the old member gone before the new
        SELECT p.company_id, p.axis, p.old, p.new, sum(p.pairs)::bigint AS matched,
               max(sb.last_filed) AS new_last_filed
        FROM pairs p
        JOIN spans sa ON sa.company_id = p.company_id AND sa.axis = p.axis
                     AND sa.canon = p.old
        JOIN spans sb ON sb.company_id = p.company_id AND sb.axis = p.axis
                     AND sb.canon = p.new
        WHERE sa.last_filed < sb.first_filed
        GROUP BY p.company_id, p.axis, p.old, p.new
    ),
    renames AS (
        SELECT DISTINCT ON (company_id, axis, old) company_id, axis, old, new
        FROM matches
        ORDER BY company_id, axis, old, matched DESC, new_last_filed DESC, new
    ),
    chain (company_id, axis, old, new, depth) AS (
        SELECT company_id, axis, old, new, 1 FROM renames
        UNION ALL
        SELECT c.company_id, c.axis, c.old, r.new, c.depth + 1
        FROM chain c
        JOIN renames r ON r.company_id = c.company_id AND r.axis = c.axis AND r.old = c.new
        WHERE c.depth < 20
    ),
    final AS (
        SELECT DISTINCT ON (company_id, axis, old) company_id, axis, old, new
        FROM chain
        ORDER BY company_id, axis, old, depth DESC
    ),
    resolved AS (
        SELECT k.*, coalesce(fn.new, k.canon) AS final_member,
               -- 062: 053's LATERAL `o`, the value as first reported at this row's tag priority,
               -- as a window (best's row carries it)
               first_value(k.value) OVER (
                   PARTITION BY k.company_id, k.axis, coalesce(fn.new, k.canon), k.metric,
                                k.period_start, k.period_end, k.priority
                   ORDER BY k.filed, k.accession_no, k.cik, k.member) AS first_reported
        FROM keyed k
        LEFT JOIN final fn ON fn.company_id = k.company_id AND fn.axis = k.axis
                          AND fn.old = k.canon
    ),
    aliases AS (  -- 062: every QName merged in, once per member (it was a sub-select per row)
        SELECT company_id, axis, final_member,
               coalesce(array_agg(DISTINCT member ORDER BY member)
                            FILTER (WHERE member <> final_member), '{}') AS aliases
        FROM resolved
        GROUP BY company_id, axis, final_member
    ),
    members AS (  -- label of the latest filing, and every QName merged in
        SELECT DISTINCT ON (r.company_id, r.axis, r.final_member)
               r.company_id, r.axis, r.final_member, r.member_label, a.aliases
        FROM resolved r
        JOIN aliases a USING (company_id, axis, final_member)  -- 062
        ORDER BY r.company_id, r.axis, r.final_member, (r.member = r.final_member) DESC,
                 r.filed DESC, r.accession_no DESC
    ),
    best AS (
        SELECT DISTINCT ON (company_id, axis, final_member, metric, period_start, period_end) *
        FROM resolved
        ORDER BY company_id, axis, final_member, metric, period_start, period_end, priority,
                 filed DESC, accession_no DESC, cik, member
    ),
    year_to_date AS (
        SELECT b.*,
               lag(value)        OVER w AS prev_value,
               lag(period_end)   OVER w AS prev_end,
               lag(accession_no) OVER w AS prev_accession,
               lag(ingested_at)  OVER w AS prev_ingested_at,
               lag(priority)     OVER w AS prev_priority,
               lag(filed)        OVER w AS prev_filed  -- 053
        FROM best b
        WINDOW w AS (PARTITION BY company_id, axis, final_member, metric, period_start
                     ORDER BY period_end)
    ),
    -- 053: when the later year-to-date value was restated (its latest filing's value differs from
    -- the first one reported), a derived quarter takes it as the first filing on or after the
    -- earlier value's filing reported it (the same reporting cycle, so the same segment basis),
    -- not the latest restatement. JPMorgan's FY2022 from its FY2024 10-K, recast for the 2024
    -- merger of Commercial Banking into CIB, less nine months from a 2023 10-Q (the old CIB) made
    -- a CIB quarter of $22.13B beside quarters of $12B. Not restated, or no such filing: the
    -- latest, as before (Vertiv's FY2023 10-K alone reported FY2022 regions differently).
    same_basis AS (
        SELECT y.company_id, y.axis, y.final_member, y.metric, y.prev_end, y.period_end,
               coalesce(r.value, y.value) - y.prev_value AS value, y.unit,
               coalesce(r.concept, y.concept) AS concept, y.axis_qname,
               coalesce(r.accession_no, y.accession_no) AS accession_no,
               coalesce(r.cik, y.cik) AS cik, coalesce(r.form, y.form) AS form,
               coalesce(r.filed, y.filed) AS filed, y.prev_accession,
               greatest(coalesce(r.ingested_at, y.ingested_at), y.prev_ingested_at)
                   AS ingested_at,
               greatest(coalesce(r.priority, y.priority), y.prev_priority) AS priority
        FROM year_to_date y
        -- 062: the first row of 053's DISTINCT ON order, as a LATERAL whose restated test is a
        -- one-time filter: only a restated value reads `resolved` (a scan of it per row before)
        LEFT JOIN LATERAL (
            SELECT r.*
            FROM resolved r
            WHERE y.first_reported IS DISTINCT FROM y.value  -- restated since: pair by cycle
              AND r.company_id = y.company_id AND r.axis = y.axis
              AND r.final_member = y.final_member AND r.metric = y.metric
              AND r.period_start = y.period_start AND r.period_end = y.period_end
              AND r.filed >= y.prev_filed
            ORDER BY r.priority = y.prev_priority DESC NULLS LAST, r.filed, r.accession_no, r.cik,
                     r.member
            LIMIT 1
        ) r ON true
        WHERE y.additive AND y.period_end - y.prev_end BETWEEN 80 AND 120
    ),
    candidates AS (
        SELECT company_id, axis, final_member, metric, period_start, period_end, value, unit,
               'reported' AS value_source, concept, axis_qname, accession_no, cik, form, filed,
               ARRAY[accession_no] AS source_accessions, ingested_at, priority
        FROM best
        WHERE period_type = 'quarter'
        UNION ALL
        SELECT company_id, axis, final_member, metric, prev_end + 1, period_end, value, unit,
               'derived', concept, axis_qname, accession_no, cik, form, filed,
               ARRAY[prev_accession, accession_no], ingested_at, priority
        FROM same_basis  -- 053
    ),
    quarters AS (
        SELECT DISTINCT ON (company_id, axis, final_member, metric, period_end) *
        FROM candidates
        ORDER BY company_id, axis, final_member, metric, period_end, priority,
                 value_source = 'reported' DESC, filed DESC, accession_no DESC,
                 source_accessions DESC, period_start DESC, concept, value, ingested_at DESC,
                 cik
    )
    INSERT INTO gold.segment_financials
        (company_id, span, axis, member, member_label, member_aliases, metric, period_start,
         period_end, value, unit, value_source, source_tag, axis_qname, accession_no,
         filer_cik, form, filed, source_accessions, ingested_at)
    SELECT q.company_id, 'quarter', q.axis, q.final_member, m.member_label, m.aliases, q.metric,
           q.period_start, q.period_end, q.value, q.unit, q.value_source, q.concept,
           q.axis_qname, q.accession_no, q.cik, q.form, q.filed, q.source_accessions,
           q.ingested_at
    FROM quarters q
    JOIN members m ON m.company_id = q.company_id AND m.axis = q.axis
                  AND m.final_member = q.final_member;
    END LOOP;  -- 062

    WITH quarters AS (
        SELECT g.*,
               coalesce(g.period_start - lag(g.period_end) OVER w BETWEEN 0 AND 7, false)
                   AS follows
        FROM gold.segment_financials g
        JOIN silver.segment_metrics m ON m.metric = g.metric
        WHERE g.company_id = ANY(p_company_ids) AND g.span = 'quarter' AND m.additive
        WINDOW w AS (PARTITION BY g.company_id, g.axis, g.member, g.metric ORDER BY g.period_end)
    ),
    windows AS (
        SELECT q.*,
               count(*) OVER w4 AS n_quarters,
               bool_and(follows) OVER w3 AS contiguous,
               first_value(period_start) OVER w4 AS ttm_start,
               sum(value) OVER w4 AS ttm_value,
               max(ingested_at) OVER w4 AS ttm_ingested_at,
               source_accessions || lag(source_accessions, 1) OVER w
                   || lag(source_accessions, 2) OVER w || lag(source_accessions, 3) OVER w
                   AS accessions
        FROM quarters q
        WINDOW w AS (PARTITION BY company_id, axis, member, metric ORDER BY period_end),
               w4 AS (w ROWS 3 PRECEDING),
               w3 AS (w ROWS 2 PRECEDING)
    )
    INSERT INTO gold.segment_financials
        (company_id, span, axis, member, member_label, member_aliases, metric, period_start,
         period_end, value, unit, value_source, source_tag, axis_qname, accession_no,
         filer_cik, form, filed, source_accessions, ingested_at)
    SELECT company_id, 'ttm', axis, member, member_label, member_aliases, metric, ttm_start,
           period_end, ttm_value, unit, 'ttm', source_tag, axis_qname, accession_no, filer_cik,
           form, filed, ARRAY(SELECT DISTINCT a FROM unnest(accessions) a ORDER BY 1),
           ttm_ingested_at
    FROM windows
    WHERE n_quarters = 4 AND contiguous AND period_end - ttm_start + 1 BETWEEN 350 AND 380;

    SELECT count(*) INTO n FROM gold.segment_financials
    WHERE company_id = ANY(p_company_ids) AND span = 'quarter';
    RETURN n;
END
$$;
